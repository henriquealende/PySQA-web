"""Builds frontend/src/pages/Docs/demoIpm.ts: the IPM of one noise burst in two sweeps, for the interactive charts of the documentation.

A noise floor (RMS 0.01) with one noise burst at 2 s (linear rise, then exponential decay).
  size sweep      the burst keeps its shape (5 ms rise, 50 ms decay) and gets smaller: 40 dB down to 0 dB above the floor.
  duration sweep  the burst keeps its size (28 dB above the floor) and gets longer: rise from 1 ms to 200 ms, decay = 10 x rise.
Each step stores the IPM computed by backend/psychoacoustics/mpi.py (the same code as the site) and a decimated copy of the
waveform around the event. Run from the backend folder (about 20 seconds):

    .venv\\Scripts\\python.exe ..\\dev-tests\\gen_docs_ipm.py
"""
import json
import os
import sys
import warnings
from pathlib import Path

import numpy as np

warnings.filterwarnings("ignore")
sys.path.insert(0, os.getcwd())
from psychoacoustics.mpi import IPM  # noqa: E402

OUT = Path("../frontend/src/pages/Docs/demoIpm.ts")
FS = 48000
DUR, AT = 4.0, 2.0
FLOOR_RMS = 0.01
SIZES_DB = [40, 34, 28, 22, 16, 12, 9, 6, 3, 0]            # peak of the burst above the floor
RISES_MS = [1, 2, 5, 10, 20, 40, 80, 120, 200]
N_SHOW = 480

rng = np.random.default_rng(11)
floor = rng.standard_normal(int(DUR * FS)) * FLOOR_RMS
burst_noise = rng.standard_normal(int(DUR * FS))
ipm = IPM()


def burst(rise_s, tau_s, db):
    n_rise = int(rise_s * FS)
    env = np.zeros(int(DUR * FS))
    i0 = int(AT * FS)
    env[i0:i0 + n_rise] = np.linspace(0, 1, n_rise)
    room = len(env) - i0 - n_rise
    tail = np.exp(-np.arange(min(int(6 * tau_s * FS), room)) / (tau_s * FS))
    env[i0 + n_rise:i0 + n_rise + len(tail)] = tail
    return floor + burst_noise * env * FLOOR_RMS * 10 ** (db / 20)


def step(x, win, **extra):
    r = ipm.analyze(x, FS)
    seg = x[int(win[0] * FS):int(win[1] * FS)]
    edges = np.linspace(0, len(seg), N_SHOW + 1).astype(int)
    wave = [float(seg[a:b][np.argmax(np.abs(seg[a:b]))]) for a, b in zip(edges[:-1], edges[1:])]
    return {**extra, "wave": [round(v, 4) for v in wave], "mpi": [round(float(v), 2) for v in r.mpi],
            "detected": [bool(v) for v in r.detected], "global": round(r.global_db, 1), "max": round(float(r.mpi.max()), 2),
            "impulsive": bool(r.impulsive), "bands_over": int(r.bands_over_threshold)}


WIN_SIZE, WIN_DUR = (1.9, 2.3), (1.9, 3.1)
size = []
for d in SIZES_DB:
    s = step(burst(0.005, 0.05, d), WIN_SIZE, db=d)
    size.append(s)
    print(f"size {d:3d} dB: bands {sum(s['detected']):2d}, max MPI {s['max']:5.2f}, global {s['global']:5.1f}, impulsive {s['impulsive']}")
dur = []
for ms in RISES_MS:
    s = step(burst(ms / 1000, 10 * ms / 1000, 28), WIN_DUR, ms=ms)
    dur.append(s)
    print(f"rise {ms:3d} ms: bands {sum(s['detected']):2d}, max MPI {s['max']:5.2f}, global {s['global']:5.1f}, impulsive {s['impulsive']}")

z = [round(float(v), 1) for v in ipm.analyze(burst(0.005, 0.05, 20), FS).z]
data = {"z": z, "window": list(WIN_SIZE), "steps": size, "windowDur": list(WIN_DUR), "durSteps": dur}
OUT.write_text("// Generated by dev-tests/gen_docs_ipm.py from the real IPM code; do not edit by hand.\nexport const DEMO_IPM = "
               + json.dumps(data, separators=(",", ":")) + "\n", encoding="utf-8", newline="\n")
print("written", OUT, OUT.stat().st_size, "bytes")
