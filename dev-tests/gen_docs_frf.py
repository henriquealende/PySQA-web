"""Builds frontend/src/pages/Docs/demoFrf.ts: real System Analysis results on a system with known modes,
used by the charts of the documentation page.

Run from the backend folder:  .venv\\Scripts\\python.exe ..\\dev-tests\\gen_docs_frf.py
"""
import json
import os
import sys
from pathlib import Path

import numpy as np

sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, os.getcwd())
import services.frf_service as frf   # noqa: E402

OUT = Path("../frontend/src/pages/Docs/demoFrf.ts")
FS = 2048.0
MODES = [(87.3, 0.020, 1.0e5), (213.6, 0.010, 6.0e4), (390.2, 0.015, 3.0e4)]


def truth(f):
    w = 2 * np.pi * f
    H = sum(r / ((2 * np.pi * fn) ** 2 - w ** 2 + 2j * z * (2 * np.pi * fn) * w) for fn, z, r in MODES)
    return -(w ** 2) * H                        # accelerance


def simulate(x, noise, seed):
    f = np.fft.rfftfreq(len(x), 1 / FS)
    y = np.fft.irfft(np.fft.rfft(x) * truth(f), n=len(x))
    return y + noise * np.std(y) * np.random.default_rng(seed).standard_normal(len(y))


def put(sid, x, y):
    frf.store_channels(sid, [frf.Channel("e_0", "force", "f", "time", x, fs=FS), frf.Channel("r_0", "acc", "f", "time", y, fs=FS)])


def r(v, n=2):
    return [round(float(a), n) for a in v]


rng = np.random.default_rng(0)
x = rng.standard_normal(int(FS * 240))
y = simulate(x, 0.05, 1)
base = dict(excitation="e_0", responses=["r_0"], nperseg=8192, overlap=50, window="hann", response_type="acceleration",
            show_as="acceleration", fmin=20, fmax=600, averaging="welch")

put("a", x, y)
clean = frf.analyse("a", dict(base, estimator="H1", modes=dict(prominence_db=10, min_sep_hz=10, method="both")))
f = np.array(clean["freqs"])
data = {
    "f": r(f, 2),
    "trueDb": r(20 * np.log10(np.abs(truth(f))), 2),
    "h1Db": clean["responses"][0]["mag_db"],
    "phase": clean["responses"][0]["phase_deg"],
    "coh": r(clean["responses"][0]["coherence"], 3),
    "mif": clean["mif_db"],
    "modes": [{"fn": m["fn_hz"], "zeta": m["zeta"], "hp": m["zeta_hp"], "fit": m["zeta_fit"], "q": m["q"], "coh": m["coherence"]} for m in clean["modes"]],
    "truth": [{"fn": fn, "zeta": z} for fn, z, _ in MODES],
    "nAvg": clean["n_averages"],
}

# the same sound, but with noise on the force as well: the three estimators part ways
xn = x + 0.7 * np.std(x) * rng.standard_normal(len(x))
put("b", xn, y)
noisy = {}
for est in ("H1", "H2", "HV"):
    q = frf.analyse("b", dict(base, estimator=est, modes=None))
    noisy[est] = q["responses"][0]["mag_db"]
data["noisy"] = {"H1": noisy["H1"], "H2": noisy["H2"], "Hv": noisy["HV"], "coh": r(frf.analyse("b", dict(base, estimator="H1", modes=None))["responses"][0]["coherence"], 3)}

# impact testing: nine hits
n = int(FS * 40)
xi = np.zeros(n)
npulse = int(0.002 * FS)
pulse = np.sin(np.pi * np.arange(npulse) / npulse) * 500.0
for k in range(9):
    h0 = int(FS * (1.0 + 4.0 * k))
    xi[h0:h0 + npulse] += pulse
xi += 0.002 * rng.standard_normal(n)
put("c", xi, simulate(xi, 0.01, 3))
imp = frf.analyse("c", dict(base, averaging="impact", nperseg=8192, estimator="H1",
                            impact=dict(trigger_pct=20, pretrigger_pct=5, force_ms=8, exp_end_pct=2),
                            modes=dict(prominence_db=10, min_sep_hz=10, method="both")))
data["impact"] = {"hits": imp["n_averages"], "decay": imp["exp_decay_rate"],
                  "modes": [{"fn": m["fn_hz"], "zeta": m["zeta"], "hp": m["zeta_hp"], "fit": m["zeta_fit"]} for m in imp["modes"]]}

OUT.write_text("// Generated by dev-tests/gen_docs_frf.py: real PySQA results on a system with known modes. Do not edit by hand.\n"
               "export const FRF_DEMO = " + json.dumps(data, separators=(",", ":")) + " as const\n", encoding="utf-8")
print("written", OUT, OUT.stat().st_size // 1024, "KB")
print(json.dumps({"modes": data["modes"], "impact": data["impact"], "nAvg": data["nAvg"]}, indent=0)[:1500])
